import * as vscode from "vscode";
import { StructuredLogger } from "../../observability/structuredLogger";
import { diagnosticHash } from "./diagnosticHash";

/**
 * Correlation context for one chat turn. Mirrors the StructuredLogger options
 * bag so every `vscode.part_reported` line can be grepped by requestId and
 * attributed to the model/endpoint that produced it.
 */
export interface PartReportTraceContext {
    requestId: string;
    model: string;
    endpoint?: string;
}

/**
 * Host-facing part classification. "other" covers future part types so the
 * trace degrades gracefully instead of throwing on unknown instances.
 */
type ReportedPartKind = "thinking" | "text" | "tool_call" | "data" | "other";

/** Structural view of LanguageModelThinkingPart (proposed API, may be absent). */
interface ThinkingLikePart {
    value: string | string[];
    id?: string;
    metadata?: Record<string, unknown>;
}

type PartConstructor = new (...args: unknown[]) => unknown;
const SAFE_METADATA_KEYS = ["display", "encrypted_content", "redactedData", "signature"] as const;

/**
 * The ThinkingPart class only exists on hosts that ship the
 * languageModelThinkingPart proposal; resolve it dynamically like
 * vscodePartEmitter.ts and streamTokenCapture.ts already do.
 */
function getThinkingPartConstructor(): PartConstructor | undefined {
    return (vscode as unknown as Record<string, unknown>).LanguageModelThinkingPart as PartConstructor | undefined;
}

/**
 * VS Code's thinking-block merge logic treats a missing id and an empty-string
 * id differently (empty ids can merge; differing defined ids cannot), so the
 * trace must distinguish all three states — a plain `id` field cannot.
 */
function describeIdState(id: string | undefined): "absent" | "empty" | "present" {
    if (id === undefined) {
        return "absent";
    }
    return id === "" ? "empty" : "present";
}

/** Shared string-shape descriptors for text and joined thinking values. */
function describeStringValue(value: string): Record<string, unknown> {
    return {
        length: value.length,
        isEmpty: value.length === 0,
        isWhitespaceOnly: value.length > 0 && value.trim().length === 0,
    };
}

/**
 * Pure shape descriptor for one host-facing part. Logs structure only:
 * allowlisted metadata key identities, counts and presence booleans — never
 * untrusted keys or values
 * (signature/encrypted_content are continuity secrets per the logging
 * sanitization rules).
 */
function describePart(part: vscode.LanguageModelResponsePart): Record<string, unknown> & { kind: ReportedPartKind } {
    const thinkingCtor = getThinkingPartConstructor();
    if (thinkingCtor && part instanceof thinkingCtor) {
        const thinking = part as unknown as ThinkingLikePart;
        const segments = Array.isArray(thinking.value) ? thinking.value : [thinking.value];
        const metadataKeys = thinking.metadata ? Object.keys(thinking.metadata).sort() : [];
        return {
            kind: "thinking",
            valueKind: Array.isArray(thinking.value) ? "array" : "string",
            segmentCount: segments.length,
            id: diagnosticHash(thinking.id),
            idState: describeIdState(thinking.id),
            metadataKeyCount: metadataKeys.length,
            metadataKeys: SAFE_METADATA_KEYS.filter((key) => metadataKeys.includes(key)),
            hasSignature: metadataKeys.includes("signature"),
            hasEncryptedContent: metadataKeys.includes("encrypted_content"),
            ...describeStringValue(segments.join("")),
        };
    }
    if (part instanceof vscode.LanguageModelTextPart) {
        return { kind: "text", ...describeStringValue(part.value) };
    }
    if (part instanceof vscode.LanguageModelToolCallPart) {
        return {
            kind: "tool_call",
            callId: diagnosticHash(part.callId),
            toolName: diagnosticHash(part.name),
            inputKeyCount: Object.keys(part.input ?? {}).length,
        };
    }
    if (part instanceof vscode.LanguageModelDataPart) {
        return {
            kind: "data",
            mimeType: diagnosticHash(part.mimeType),
            byteLength: part.data.byteLength,
            isUsage: part.mimeType === "usage",
        };
    }
    return {
        kind: "other",
        constructorName: (part as { constructor?: { name?: string } }).constructor?.name,
    };
}

/**
 * Wraps the HOST progress (the one VS Code passed to
 * provideLanguageModelChatResponse) so that every part the connector reports
 * — streamed, recovery-flushed, or usage generated by StreamTokenCapture —
 * produces exactly one `vscode.part_reported` trace line BEFORE the host sees
 * the part.
 *
 * Invariants:
 * - The part is forwarded by reference, unmodified, exactly once, in order.
 * - `reportSeq` is request-local and strictly increasing (1-based), so the
 *   full host-facing sequence can be reconstructed from logs even when
 *   concurrent requests interleave (each turn gets its own wrapper instance).
 * - A logging failure must never break the stream: describe/log is wrapped in
 *   try/catch and the forward always happens.
 *
 * Why here and not in vscodePartEmitter: the emitter only sees interpreter
 * batches; StreamTokenCapture forwards and *generates* parts (flushUsage)
 * directly on its inner progress, bypassing the emitter. Wrapping the host
 * progress is the only single choke point.
 */
export function createPartReportTrace(
    inner: vscode.Progress<vscode.LanguageModelResponsePart>,
    context: PartReportTraceContext
): vscode.Progress<vscode.LanguageModelResponsePart> {
    let reportSeq = 0;
    let previousKind: ReportedPartKind | undefined;
    const createdAt = Date.now();

    return {
        report: (part: vscode.LanguageModelResponsePart): void => {
            reportSeq += 1;
            try {
                const detail = describePart(part);
                StructuredLogger.trace(
                    "vscode.part_reported",
                    {
                        reportSeq,
                        previousKind,
                        elapsedMs: Date.now() - createdAt,
                        ...detail,
                    },
                    { requestId: context.requestId, model: context.model, endpoint: context.endpoint }
                );
                previousKind = detail.kind;
            } catch {
                // Diagnostics must never break the stream; swallow and forward.
            }
            inner.report(part);
        },
    };
}
